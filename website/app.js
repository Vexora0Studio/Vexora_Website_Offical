function generateGroundedAnswer(question) {
  const q = question.toLowerCase();
  const isAr = /[\u0600-\u06FF]/.test(question) || currentLang === "ar";

  if (q.includes("خدم") || q.includes("service") || q.includes("offer") || q.includes("تقدم")) {
    const items = STUDIO_DATA.services
      .map((s) => `• ${isAr ? s.titleAr : s.titleEn}: ${isAr ? s.descAr : s.descEn}`)
      .join("\n");
    return isAr ? `تقدم Vexora Studio الخدمات التالية:\n${items}` : `Vexora Studio offers:\n${items}`;
  }

  if (q.includes("مشروع") || q.includes("مشاريع") || q.includes("موقع") || q.includes("project") || q.includes("website") || q.includes("f.cut")) {
    const items = STUDIO_DATA.projects
      .map((p) => `• ${isAr ? p.nameAr : p.nameEn} (${p.url})`)
      .join("\n");
    return isAr ? `إليك أبرز مشاريع ومنصات Vexora Studio:\n${items}` : `Here are Vexora Studio's live projects:\n${items}`;
  }

  if (q.includes("فريق") || q.includes("موظف") || q.includes("team") || q.includes("omar") || q.includes("عمر") || q.includes("ceo")) {
    const items = STUDIO_DATA.team
      .map((m) => `• ${isAr ? m.nameAr : m.nameEn} — ${isAr ? m.roleAr : m.roleEn} (${m.exp} ${isAr ? "سنوات خبرة" : "yrs exp"})`)
      .join("\n");
    return isAr ? `فريق عمل Vexora Studio:\n${items}` : `Vexora Studio team members:\n${items}`;
  }

  if (q.includes("وظيف") || q.includes("توظيف") || q.includes("تقديم") || q.includes("job") || q.includes("career") || q.includes("apply")) {
    const items = STUDIO_DATA.jobs
      .map((j) => `• ${isAr ? j.titleAr : j.titleEn} (${isAr ? j.locationAr : j.locationEn})`)
      .join("\n");
    return isAr
      ? `الوظائف المتاحة حالياً:\n${items}\nيمكنك التقديم مباشرة من تبويب "التقديم على وظيفة" وإرفاق سيرتك الذاتية PDF.`
      : `Open positions right now:\n${items}\nYou can apply directly in the "Apply for a Role" tab with your PDF CV.`;
  }

  if (q.includes("تواصل") || q.includes("بريد") || q.includes("contact") || q.includes("email")) {
    return isAr
      ? `يمكنك التواصل مع Vexora Studio عبر البريد الرسمي: ${STUDIO_DATA.email} أو من خلال نموذج "تواصل معنا" في أسفل الصفحة.`
      : `You can reach Vexora Studio via our official email: ${STUDIO_DATA.email} or via the Contact form below.`;
  }

  return isAr
    ? `في Vexora Studio نعمل في تطوير المواقع، تطبيقات Android، الذكاء الاصطناعي، تصميم UI/UX، والجرافيك والمونتاج. اسألني تحديداً عن: الخدمات، المشاريع، الفريق، الوظائف، أو التواصل (${STUDIO_DATA.email}).`
    : `At Vexora Studio we specialize in Web platforms, Android apps, AI solutions, UI/UX, and creative media. Ask specifically about Services, Projects, Team, Careers, or Contact (${STUDIO_DATA.email}).`;
}

function handleAiQuestion(text) {
  const clean = text.trim();
  if (!clean) return;
  appendChatBubble(clean, "user");
  setTimeout(() => {
    appendChatBubble(generateGroundedAnswer(clean), "bot");
  }, 220);
}

function animateStats() {
  const statsGrid = document.getElementById("statsGrid");
  const values = statsGrid.querySelectorAll(".stat-value");
  let animated = false;

  const run = () => {
    if (animated) return;
    animated = true;
    values.forEach((el) => {
      const target = Number(el.dataset.target || 0);
      let current = 0;
      const step = Math.max(1, Math.ceil(target / 24));
      const timer = setInterval(() => {
        current = Math.min(target, current + step);
        el.textContent = `${current}+`;
        if (current >= target) clearInterval(timer);
      }, 28);
    });
  };

  if ("IntersectionObserver" in window) {
    const observer = new IntersectionObserver((entries) => {
      if (entries.some((e) => e.isIntersecting)) {
        run();
        observer.disconnect();
      }
    });
    observer.observe(statsGrid);
  } else {
    run();
  }
}

