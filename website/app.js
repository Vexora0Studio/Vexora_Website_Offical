let currentLang = localStorage.getItem("vexora_lang") === "en" ? "en" : "ar";
let selectedServiceCategory = "all";
let selectedProjectStatus = "all";
let selectedCvFile = null;

function t(key) {
  return I18N[currentLang][key] || key;
}

function showToast(msg) {
  const toast = document.getElementById("toast");
  toast.textContent = msg;
  toast.hidden = false;
  clearTimeout(showToast._timer);
  showToast._timer = setTimeout(() => {
    toast.hidden = true;
  }, 3200);
}

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("vexora_lang", lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  document.getElementById("langToggleLabel").textContent = t("langToggle");

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (I18N[lang][key]) {
      el.textContent = I18N[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (I18N[lang][key]) {
      el.placeholder = I18N[lang][key];
    }
  });

  renderServiceFilters();
  renderServices();
  renderProjectFilters();
  renderProjects();
  renderTeam();
  renderJobs();
  renderQuickPrompts();

  const chatBox = document.getElementById("chatMessages");
  if (chatBox.children.length === 0) {
    appendChatBubble(t("aiWelcome"), "bot");
  }
}

function renderServiceFilters() {
  const container = document.getElementById("serviceFilters");
  const categories = [
    { key: "all", label: t("allCategories") },
    { key: "web", label: currentLang === "ar" ? "الويب" : "Web" },
    { key: "mobile", label: currentLang === "ar" ? "الجوال" : "Mobile" },
    { key: "ai", label: currentLang === "ar" ? "الذكاء الاصطناعي" : "AI" },
    { key: "design", label: currentLang === "ar" ? "التصميم" : "Design" },
    { key: "media", label: currentLang === "ar" ? "الإنتاج" : "Media" },
    { key: "engineering", label: currentLang === "ar" ? "البرمجيات" : "Engineering" }
  ];

  container.innerHTML = categories
    .map(
      (cat) =>
        `<button type="button" class="chip-btn ${selectedServiceCategory === cat.key ? "active" : ""}" data-cat="${cat.key}">${cat.label}</button>`
    )
    .join("");

  container.querySelectorAll(".chip-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      selectedServiceCategory = btn.dataset.cat;
      renderServiceFilters();
      renderServices();
    });
  });
}

function renderServices() {
  const grid = document.getElementById("servicesGrid");
  const list =
    selectedServiceCategory === "all"
      ? STUDIO_DATA.services
      : STUDIO_DATA.services.filter((s) => s.category === selectedServiceCategory);

  grid.innerHTML = list
    .map(
      (s) => `
      <article class="glass-card service-card">
        <div class="service-icon-box" aria-hidden="true">${s.icon}</div>
        <h3 class="card-title">${currentLang === "ar" ? s.titleAr : s.titleEn}</h3>
        <p class="card-desc">${currentLang === "ar" ? s.descAr : s.descEn}</p>
      </article>
    `
    )
    .join("");
}

