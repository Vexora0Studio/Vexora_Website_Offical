function normalizeRoute(r) {
  const valid = ["home", "services", "projects", "team", "download", "contact", "admin"];
  return valid.includes(r) ? r : null;
}

function t(key) {
  return I18N[currentLang][key] || key;
}

function isArabic() {
  return currentLang === "ar";
}

function isAdminUnlocked() {
  return sessionStorage.getItem(ADMIN_SESSION_KEY) === "1";
}

function verifyAdminCode(input) {
  const value = String(input || "");
  if (value.length !== ADMIN_CODE_POINTS.length) return false;
  let diff = 0;
  for (let i = 0; i < ADMIN_CODE_POINTS.length; i++) {
    diff |= value.charCodeAt(i) ^ ADMIN_CODE_POINTS[i];
  }
  return diff === 0;
}

function escapeHtml(str) {
  return String(str || "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function showToast(msg) {
  const toast = document.getElementById("toast");
  toast.textContent = msg;
  toast.hidden = false;
  clearTimeout(showToast._timer);
  showToast._timer = setTimeout(() => {
    toast.hidden = true;
  }, 3000);
}

