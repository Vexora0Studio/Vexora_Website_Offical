function normalizeRoute(r) {
  const valid = ["home", "services", "projects", "team_careers", "ai", "contact", "admin"];
  return valid.includes(r) ? r : null;
}

function t(key) {
  return I18N[currentLang][key] || key;
}

function isArabic() {
  return currentLang === "ar";
}

function isAdminUser() {
  const email = (studioState.user?.email || "").trim().toLowerCase();
  return ADMIN_EMAILS.includes(email);
}

function escapeHtml(str) {
  return String(str || "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function showToast(msg) {
  const toast = document.getElementById("toast");
  toast.textContent = msg;
  toast.hidden = false;
  clearTimeout(showToast._timer);
  showToast._timer = setTimeout(() => {
    toast.hidden = true;
  }, 3000);
}

function serviceIconGlyph(key) {
  switch ((key || "").toLowerCase()) {
    case "web": return "🌐";
    case "android":
    case "mobile": return "📱";
    case "ai": return "✨";
    case "palette":
    case "graphic": return "🎨";
    case "video":
    case "media": return "🎬";
    case "uiux": return "🧩";
    default: return "⚡";
  }
}

function projectImageSrc(proj) {
  if (proj.imageUrl) return proj.imageUrl;
  return STUDIO_IMAGES[proj.presetImageKey] || STUDIO_IMAGES.web;
}

function statusMeta(status) {
  if (status === "available") return { label: t("statusAvailable"), cls: "success" };
  if (status === "in_development") return { label: t("statusInDevelopment"), cls: "warning" };
  return { label: t("statusCompleted"), cls: "cyan" };
}

