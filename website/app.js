function openModal(title, htmlContent) {
  document.getElementById("modalTitle").textContent = title;
  document.getElementById("modalBody").innerHTML = htmlContent;
  document.getElementById("modalBackdrop").hidden = false;
}

function closeModal() {
  document.getElementById("modalBackdrop").hidden = true;
}

function openMemberCvModal(memberId) {
  const m = studioState.team.find((x) => x.id === memberId);
  if (!m) return;
  const name = isArabic() ? m.nameAr : m.nameEn;
  const role = isArabic() ? m.roleAr : m.roleEn;
  const summary = (isArabic() ? m.cvSummaryAr : m.cvSummaryEn) || (isArabic() ? m.bioAr : m.bioEn);

  openModal(
    t("cvDetailsTitle"),
    `
    <h3 class="card-title">${escapeHtml(name)}</h3>
    <div style="color:var(--neon-cyan);font-size:0.9rem;">${escapeHtml(role)}</div>
    <hr style="border:none;border-top:1px solid var(--glass-white-border);width:100%;" />
    <p style="margin:0;">${escapeHtml(summary)}</p>
    <p class="muted-text">${escapeHtml((m.skills || []).join(" • "))}</p>
    ${
      m.cvPdfBase64
        ? `<button id="modalOpenPdfBtn" type="button" class="btn btn-primary btn-full">📄 ${escapeHtml(t("viewDownloadPdf"))}</button>`
        : ""
    }
  `
  );
  const btn = document.getElementById("modalOpenPdfBtn");
  if (btn) {
    btn.addEventListener("click", () => openPdfPreviewModal(m.cvFileName || `${m.nameEn}_CV.pdf`, m.cvPdfBase64));
  }
}

function openPdfPreviewModal(fileName, base64) {
  const dataUri = `data:application/pdf;base64,${base64}`;
  openModal(
    fileName,
    `
    <iframe class="pdf-frame" src="${dataUri}" title="${escapeHtml(fileName)}"></iframe>
    <a class="btn btn-primary btn-full" href="${dataUri}" download="${escapeHtml(fileName)}">⬇️ ${escapeHtml(t("savePdfToDevice"))}</a>
  `
  );
}

